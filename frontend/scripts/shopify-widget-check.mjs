// REQ-467..476 check: Shopify sub-tabs, redirects, guard, links. node scripts/shopify-widget-check.mjs [baseUrl]
import { chromium } from 'playwright-core'

const BASE = process.argv[2] ?? 'http://localhost:4173'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const p = await ctx.newPage()
const errors = []
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const log = (...a) => console.log(...a)
const path = () => { const u = new URL(p.url()); return u.pathname + u.search }
await p.goto(`${BASE}/login`)
await p.fill('input[type=email]', 'ava@goorin.com')
await p.fill('input[type=password]', 'goorin123')
await p.getByRole('button', { name: 'Sign in' }).click()
await p.waitForURL('**/dashboard')

await p.goto(`${BASE}/settings/integrations`)
await p.waitForSelector('[data-testid=integration-tile-shopify]')
log('settings tabs:', (await p.locator('[data-testid^=settings-tab-]:not([data-testid$=-alert])').allInnerTexts()).join(' | '))
log('tile sub-status:', await p.innerText('[data-testid=integration-widget-status-shopify]'))
await p.click('[data-testid=integration-tile-shopify]')
await p.waitForSelector('[data-testid=shopify-widget-summary]')
log('overview:', path(), '| summary:', (await p.innerText('[data-testid=shopify-widget-summary]')).replace(/\s+/g, ' '), '| test btn:', await p.isVisible('[data-testid=test-connection-shopify]'), '| creds:', await p.isVisible('[data-testid=integration-section-credentials]'))
await p.waitForTimeout(400)
await p.screenshot({ path: '/tmp/shopify-overview-1440.png' })
await p.click('[data-testid=shopify-customize-widget]')
await p.waitForSelector('[data-testid=widget-settings-form]')
await p.waitForSelector('[data-testid=preview-surface]')
const sections = await p.locator('[data-testid=widget-settings-form] > *').count()
log('widget:', path(), '| sections:', sections, '| preview aside:', await p.isVisible('aside[aria-label="Live preview"]'))
await p.waitForTimeout(800)
await p.screenshot({ path: '/tmp/shopify-widget-1440.png' })
const formW = await p.$eval('[data-testid=widget-settings-form]', (e) => Math.round(e.getBoundingClientRect().width))
log('editor form width:', formW)
// guard on sub-tab switch
await p.click('text=Conversation')
const firstText = p.locator('[data-testid=widget-settings-form] input:not([type=color]):not([type=file]):not([type=checkbox]):not([type=radio]):not([type=range]):visible').first()
await firstText.fill('Goorin Help Desk test')
await p.waitForSelector('[data-testid=ws-save]')
await p.click('[data-testid=channels-tab-install]')
log('guard dialog on sub-tab:', await p.isVisible('[data-testid=unsaved-dialog]'))
await p.click('[data-testid=unsaved-discard]')
await p.waitForURL('**/channels/install')
await p.waitForSelector('[data-testid=channels-install], [data-testid=widget-install]')
log('install:', path(), '| save bar:', await p.isVisible('[data-testid=ws-save]'), '| text:', (await p.innerText('[data-testid=channels-install]')).slice(0, 90).replace(/\s+/g, ' '))
// redirects
await p.goto(`${BASE}/settings/widget`); await p.waitForTimeout(900); log('redirect /settings/widget →', path())
await p.goto(`${BASE}/settings/widget#install`); await p.waitForTimeout(900); log('redirect #install →', path())
// csat round trip
await p.goto(`${BASE}/channels/chat`)
await p.waitForSelector('[data-testid=widget-settings-form]')
await p.click('text=CSAT in chat')
await p.click('[data-testid=ws-edit-questions]')
await p.waitForSelector('[data-testid=csat-settings-tab]')
log('csat settings at', path())
await p.waitForTimeout(800)
await p.goBack()
await p.waitForURL((u) => u.pathname === '/channels/chat', { timeout: 5000 }).catch(() => {})
log('csat close returns to', path())
// theme editor links
await p.goto(`${BASE}/widget-demo/theme-editor`)
await p.waitForSelector('[data-testid=te-back]')
log('te-back →', await p.getAttribute('[data-testid=te-back]', 'href'), '| te-helper-link →', await p.getAttribute('[data-testid=te-helper-link]', 'href').catch(() => 'n/a'))
log('console errors:', errors.length, errors.slice(0, 2).join(' | '))
await ctx.close()
// phone
const ph = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
const q = await ph.newPage()
await q.goto(`${BASE}/login`)
await q.fill('input[type=email]', 'ava@goorin.com')
await q.fill('input[type=password]', 'goorin123')
await q.getByRole('button', { name: 'Sign in' }).click()
await q.waitForURL('**/dashboard')
await q.goto(`${BASE}/settings/integrations/shopify/widget`)
await q.waitForURL('**/channels/chat', { timeout: 5000 }).catch(() => {})
log('phone legacy shopify/widget →', new URL(q.url()).pathname)
await q.waitForSelector('[data-testid=widget-preview-open]')
const nav = await q.$eval('[data-testid=channels-tab-chat]', (t) => { const e = t.closest('nav,[role=tablist]') ?? t.parentElement; return `${getComputedStyle(e).overflowX} scrollW=${e.scrollWidth} clientW=${e.clientWidth} docOverflow=${document.documentElement.scrollWidth > innerWidth}` })
log('phone channels tabs:', nav, '| preview btn:', await q.isVisible('[data-testid=widget-preview-open]'))
await q.screenshot({ path: '/tmp/shopify-widget-390.png' })
await browser.close()
